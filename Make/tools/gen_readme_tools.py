"""Rewrite the tool list in README.md from the tool definitions.

The block between the markers below is generated; edit the tools, not the
block. Reads the source with ast and the tool data as JSON, so it needs
neither FreeCAD nor Agent Link. This add-on's own copy (Workshop add-ons
share no library).

    python3 tools/gen_readme_tools.py          # rewrite README.md
    python3 tools/gen_readme_tools.py --check  # exit 1 if it is out of date
"""
import ast
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEGIN = "<!-- tools:begin (generated by tools/gen_readme_tools.py) -->"
END = "<!-- tools:end -->"
# Where the tools are defined: a fam_*.py (its Tool(...) calls, group from
# its GROUP) or a data/tools.json (Agent Link's tool-data format, group per
# entry). (source file, group shown; None: the source's own group)
SOURCES = [("workshop_make/data/tools.json", None)]
# A tool whose first sentence reads badly cut short: the line shown instead.
SHORT = {}


def _const(node):
    return node.value if isinstance(node, ast.Constant) and isinstance(node.value, str) else None


def _lead(node, names):
    """The text a description starts with: a literal, the left end of a
    concatenation, or a name assigned one of those."""
    while isinstance(node, ast.BinOp):
        node = node.left
    if isinstance(node, ast.Name):
        return names.get(node.id)
    return _const(node)


def _short(desc, limit=110):
    """The first sentence, without its argument details."""
    s = desc
    for _ in range(3):
        s = re.sub(r"\s*\([^()]*\)", "", s)
        s = re.sub(r"\s*\{[^{}]*\}", "", s)
        s = re.sub(r"\s*\[[^\[\]]*\]", "", s)
    s = re.split(r"(?<=[.!?])\s|\s—\s|:\s|\s\|\s", s.strip(), maxsplit=1)[0].strip().rstrip(".;,")
    if len(s) > limit:
        return s[:limit].rsplit(" ", 1)[0].rstrip(",;").replace("|", "\\|") + " …"
    return s.replace("|", "\\|") + "."


def _read_py(path):
    tree = ast.parse(open(path, encoding="utf-8").read())
    group, names, found = None, {}, []
    for n in tree.body:
        if isinstance(n, ast.Assign) and any(getattr(t, "id", None) == "GROUP" for t in n.targets):
            group = _const(n.value)
    for n in ast.walk(tree):
        if isinstance(n, ast.Assign) and len(n.targets) == 1 and isinstance(n.targets[0], ast.Name):
            lead = _lead(n.value, names)
            if lead is not None:
                names[n.targets[0].id] = lead
    for n in ast.walk(tree):
        if isinstance(n, ast.Call) and getattr(n.func, "id", getattr(n.func, "attr", None)) == "Tool" and len(n.args) >= 2:
            name = _const(n.args[0])
            if name:
                found.append((n.lineno, name, group, _lead(n.args[1], names) or ""))
    return [row[1:] for row in sorted(found)]


def _read_json(path):
    with open(path, encoding="utf-8") as f:
        entries = json.load(f)["entries"]
    return [(name, e.get("group"), e.get("description", "")) for name, e in entries.items()]


def read(path):
    """[(tool, group, description)] in the source's order."""
    full = os.path.join(ROOT, path)
    return _read_json(full) if path.endswith(".json") else _read_py(full)


def block():
    rows = ["| Tool | Group | What it does |", "|---|---|---|"]
    for path, label in SOURCES:
        for name, group, desc in read(path):
            rows.append(f"| `{name}` | {label or group or ''} | {SHORT.get(name) or _short(desc)} |")
    return "\n".join([BEGIN, *rows, END])


def render(text):
    i, j = text.find(BEGIN), text.find(END)
    if i < 0 or j < i:
        raise SystemExit("README.md has no tools block (markers missing)")
    return text[:i] + block() + text[j + len(END):]


def main(argv):
    readme = os.path.join(ROOT, "README.md")
    old = open(readme, encoding="utf-8").read()
    new = render(old)
    if "--check" in argv:
        if new != old:
            print("README.md tool list is out of date: run python3 tools/gen_readme_tools.py")
            return 1
        return 0
    if new != old:
        open(readme, "w", encoding="utf-8").write(new)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
